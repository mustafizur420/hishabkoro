const MAX_KEY = Math.max(...Object.keys(U2B).map((k) => k.length));

/** একটা যুক্তাক্ষর-গুচ্ছকে বাঁ থেকে লম্বা-মিল ধরে রূপান্তর (রিকারশন নেই) */
function convertCluster(s: string): string {
  let out = '';
  let i = 0;
  while (i < s.length) {
    let hit = '';
    for (let len = Math.min(MAX_KEY, s.length - i); len > 0; len--) {
      const part = s.slice(i, i + len);
      if (U2B[part] !== undefined) {
        hit = part;
        break;
      }
    }
    if (hit) {
      out += U2B[hit];
      i += hit.length;
    } else {
      out += s[i];
      i += 1;
    }
  }
  return out;
}

// রেফ? + অক্ষর(হসন্ত+অক্ষর)* + (ZWJ? য/র/ল-ফলা)? + কার?  |  একক চিহ্ন
const U2B_RE =
  /(র্)?([অ-হড়ঢ়য়](?:্[অ-মশ-হড়ঢ়য়])*)(‍?(্[যরল]))?([া-ৌ])?|[্ঁঃংৎ০-৯]/g;

export function unicodeToBijoy(input: string): string {
  // NFC য়/ড়/ঢ়-কে দুই অংশে ভাঙে; বিজয়ের জন্য এক অক্ষরে জোড়া লাগাই
  const s = input
    .normalize('NFC')
    .replace(/য়/g, 'য়')
    .replace(/ড়/g, 'ড়')
    .replace(/ঢ়/g, 'ঢ়')
    // বিজয়ে “ ‘ ’ – — অক্ষরের অংশ (ু, ্তু, ্থ, ্ত), তাই আগেই বিজয়ের নিজস্ব উদ্ধৃতি ও ড্যাশ চিহ্নে বদলাই
    .replace(/“/g, 'Ò')
    .replace(/”/g, 'Ó')
    .replace(/‘/g, 'Ô')
    .replace(/’/g, 'Õ')
    .replace(/[—–]/g, 'Ñ')
    .replace(/।/g, '|');

  const out = s.replace(
    U2B_RE,
    (match: string, reff: string, unit: string, phala: string, phalaSign: string, kaar: string, offset: number, whole: string) => {
      if (!unit) return U2B[match] ?? match; // একক চিহ্ন
      if (!reff && !phala && !kaar && U2B[match] !== undefined) return U2B[match];

      let main = convertCluster(unit);
      if (phala) main += U2B[phalaSign];
      if (reff) main += '©';
      if (kaar) {
        if ('াীুূৃ'.includes(kaar)) {
          // রু, রূ-এর আলাদা রূপ
          if (unit === 'র' && !phala && !reff && (kaar === 'ু' || kaar === 'ূ')) main = U2B['র' + kaar];
          else main += U2B[kaar];
        } else if ('িেৈ'.includes(kaar)) {
          main = U2B[kaar] + main;
        } else if (kaar === 'ো') {
          main = '‡' + main + 'v';
        } else if (kaar === 'ৌ') {
          main = '‡' + main + 'Š';
        }
        // শব্দের শুরুতে ে/ো হলে বিজয়ে সাধারণত † লেখা হয়
        if ((kaar === 'ে' || kaar === 'ো' || kaar === 'ৌ') && (offset === 0 || /\s/.test(whole[offset - 1]))) {
          main = main.replace('‡', '†');
        }
      }
      return main;
    },
  );

  return out;
}
